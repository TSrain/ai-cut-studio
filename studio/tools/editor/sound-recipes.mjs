export function templateSoundClip(instance, staged, fps, canvasDurationFrames) {
 const recipe=soundRecipes[instance.assetId];if(!recipe?.file)throw Error('此模板默认留白，可在声音库自选');
 const localFrame=Math.round(recipe.offsetSeconds*fps)-(instance.sourceOffsetFrames??0);
 if(localFrame<0||localFrame>=instance.durationFrames)throw Error('默认声音落点已被裁掉，请在声音库手动添加');
 const total=Math.floor(staged.durationSeconds*fps),start=instance.startFrame+localFrame;
 if(!Number.isFinite(total)||total<1)throw Error('无法读取音效时长');
 const duration=Math.min(total,instance.durationFrames-localFrame,canvasDurationFrames-start);
 if(duration<1)throw Error('声音超出时间轴');
 return {id:`sfx-${instance.id}`,name:`待试听 · ${recipe.name}`,path:staged.path,originalPath:recipe.file,startFrame:start,durationFrames:duration,sourceInFrame:0,sourceDurationFrames:total,volume:10**(recipe.gainDb/20),fadeInFrames:0,fadeOutFrames:Math.min(duration,Math.round(.04*fps))};
}
