#!/usr/bin/env node
import {existsSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {PRESET_DOCS_ROOT, readPresetCatalog} from './lib/preset-catalog.mjs';

const root = join(PRESET_DOCS_ROOT, '../..');
const require = createRequire(join(root, 'templates/remotion-base/package.json'));

async function compileSchemas() {
  const result = await require('esbuild').build({entryPoints: [join(root, 'templates/remotion-base/src/presets/index.tsx')], bundle: true, platform: 'node', format: 'esm', write: false});
  const hadFontFace = Object.hasOwn(globalThis, 'FontFace');
  const hadDocument = Object.hasOwn(globalThis, 'document');
  const previousFontFace = globalThis.FontFace;
  const previousDocument = globalThis.document;
  try {
    if (!hadFontFace) globalThis.FontFace = class {load() { return Promise.resolve(this); }};
    if (!hadDocument) globalThis.document = {fonts: {add() {}}};
    const module = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString('base64')}#${Date.now()}`);
    await new Promise((resolvePromise) => setImmediate(resolvePromise));
    return Object.fromEntries(module.PRESET_COMPOSITIONS.map((entry) => [entry.id, entry.schema.toJSONSchema()]));
  } finally {
    if (hadFontFace) globalThis.FontFace = previousFontFace; else delete globalThis.FontFace;
    if (hadDocument) globalThis.document = previousDocument; else delete globalThis.document;
  }
}

export async function generateEditorCatalog() {
  const schemas = await compileSchemas();
  const catalog = readPresetCatalog().map((preset) => {
    const slotSchemas = schemas[preset.compositionId]?.properties?.slots?.properties ?? {};
    const slots = Object.fromEntries(Object.entries(preset.slots ?? {}).map(([key, descriptor]) => {
      const schema = slotSchemas[key] ?? {};
      return [key, {...descriptor, ...(schema.minimum === undefined ? {} : {min: schema.minimum}), ...(schema.maximum === undefined ? {} : {max: schema.maximum}), ...(schema.type === 'integer' ? {integer: true} : {})}];
    }));
    return {id: preset.id, name: preset.name, compositionId: preset.compositionId, version: preset.version, status: preset.status, description: preset.description ?? preset.objectiveTemplate ?? '', thumbnail: existsSync(join(PRESET_DOCS_ROOT, `../catalog/thumbnails/remotion/preset-${preset.id}.png`)) ? `/docs/catalog/thumbnails/remotion/preset-${preset.id}.png` : null, preview: `/assets/previews/presets/${preset.id}.mp4`, canvas: preset.canvas, duration: preset.duration, slots, variants: preset.variants ?? {}, output: preset.output ?? {mode: 'opaque'}};
  });
  const target = join(root, 'templates/remotion-base/src/editor/preset-catalog.generated.ts');
  writeFileSync(target, `// Generated by tools/generate-editor-catalog.mjs from docs and PRESET_COMPOSITIONS schemas.\n// Do not hand edit.\nexport const GENERATED_PRESET_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n`);
  const schemaTarget = join(root, 'tools/lib/editor-preset-schemas.generated.json');
  writeFileSync(schemaTarget, `${JSON.stringify(schemas, null, 2)}\n`);
  console.log(`Wrote ${catalog.length} presets and schemas`);
  return {catalog, schemas};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generateEditorCatalog();
