/**
 * 口播字幕层 —— 版式规格
 *
 * 每个数字都来自 workspace/learn/dy-7543853957756489003 的逐帧像素测量,
 * 不是设计手感。改任何一个值之前先回去看 STUDY.md 第三节的实测表。
 *
 * ⚠️ 几何全部写成"占画幅的比例"而不是像素,所以竖屏 / 横屏只差一套 LAYOUT 常数,
 *    组件代码一行都不用动 —— 2026-08-28 补齐了横屏那套(LAYOUT_LANDSCAPE)。
 *    **但不是照搬**:BASELINE=0.70 是从抖音竖屏的 UI 遮挡推出来的,而 INK 是"占画幅高的比例",
 *    照搬到 1080 高的横屏上字会小掉 44%。两处差异见 LAYOUT_LANDSCAPE 的注释。
 */

export type Canvas = {width: number; height: number; fps: number};

/** 竖屏 1080×1920。实测来源见 STUDY.md 三、量出来的参数 */
export const LAYOUT_PORTRAIT = {
  /** 字幕块**底边**所在高度。实测 p10 0.645 / 中位 0.700 / p90 0.707 —— 几乎不动 */
  baseline: 0.700,
  /** 左右安全边距。实测 x 最小 10.8%,最大 88.5% */
  sideMargin: 0.11,
  /** 单行最大宽度。超过就该拆句,不是缩字号 */
  maxLineWidth: 0.78,
  /** 相邻两行**墨迹框**之间的间隙(占画幅高)。实测:标签行底 64% → 术语行顶 66% */
  lineGap: 0.020,
  /** INK 档位的整体倍率。竖屏是标定基准,恒为 1 */
  inkScale: 1,
  /** 排版器给上下行做对角错位时,两行中心的目标间距(占画幅宽) */
  stagger: 0.17,
} as const;

export type Layout = typeof LAYOUT_PORTRAIT;

/**
 * 横屏 1920×1080。**不是把竖屏那套数字照搬过来**——照搬会同时错两头:
 *
 * ① `baseline: 0.70` 是从抖音竖屏的 UI 遮挡推出来的(底部那条评论/按钮带)。
 *    横屏没有这个约束,字幕该回到画面底部,实测习惯位置是 86–90%,这里取 0.88。
 * ② `INK` 是"占**画幅高**的比例"。横屏高度只有 1080,同一个比例算出来的字
 *    只有竖屏的 56%,而画幅还宽了一倍 —— 一行 10 个字只占 21% 宽,像一条注脚。
 *    所以横屏要把整套档位放大:`inkScale 1.5` 让叙述行的墨高回到 5.4% 画幅高
 *    (1080 上 58px,字号 62px),这是 16:9 上"能当主角"的下限。
 * ③ `maxLineWidth` 反过来要**收紧**:0.78 × 1920 = 1497px ≈ 24 个字,一行读不完。
 *    0.62 ≈ 19 字,和竖屏一行的阅读量相当。
 * ④ 错位量同理收窄:横屏的行相对画幅窄,0.17 的错位会把两行拉成两座孤岛。
 *
 * 选哪一套由 `CaptionLayer` 按 `useVideoConfig()` 的宽高比自动判定,脚本不用管。
 */
export const LAYOUT_LANDSCAPE = {
  baseline: 0.880,
  sideMargin: 0.08,
  maxLineWidth: 0.62,
  lineGap: 0.024,
  inkScale: 1.5,
  stagger: 0.11,
} as const;

/** 按画幅宽高比选版式。宽 > 高 = 横屏 */
export const layoutFor = (width: number, height: number): Layout =>
  width > height ? LAYOUT_LANDSCAPE : LAYOUT_PORTRAIT;

/**
 * 字号阶梯 —— 六档,每档有固定职务,不是随手放大。
 * 值是**墨迹高度**占画幅高的比例(实测口径),不是 font-size。
 * font-size 由 INK_RATIO 反推,见下。
 * 实测比例 37 : 43 : 50 : 59 : 67 : 91 = 1 : 1.16 : 1.35 : 1.60 : 1.81 : 2.46
 */
export const INK = {
  narration: 0.0361, // 37/1024 —— 单行叙述,全片用得最多
  label: 0.0420, // 43/1024 —— 双行块的"第 N 个状态"那行
  term: 0.0488, // 50/1024 —— 双行块的术语行,比标签行大一档
  emphasis: 0.0576, // 59/1024 —— 整行强调(绝对的主导权)
  node: 0.0654, // 67/1024 —— 整屏排版图的节点词
  number: 0.0889, // 91/1024 —— 数字。全片唯一一个 80%,单独占一屏
} as const;

export type Role = keyof typeof INK;

/**
 * 墨迹高度 ÷ font-size。**这个值是渲完量回来校准的,不是拍的。**
 *
 * 标定过程(2026-08-17):先按 0.86 渲一版,用和原片完全相同的判据量墨高,
 * 得到 汉字 1.093× / 数字 0.891× 的系统性偏差 → 反推真实比值:
 *   汉字 0.86 × 1.093 = 0.940
 *   数字 0.86 × 0.891 = 0.766
 *
 * ⚠️ 汉字和拉丁数字必须分开:数字的墨迹在字身框里占比明显小,
 *    用同一个比值会让「80%」这种数字档小掉一成——正好是原片最想放大的那一档。
 *    换字体要重新标定一次,别沿用。
 */
export const INK_RATIO_CJK = 0.940;
export const INK_RATIO_LATIN = 0.766;

/**
 * 用**这一行实际的字**来选比值,而不是用它的 role。
 *
 * 起因:第一版把 0.766 绑在 `number` role 上,因为标定用的「80%」是纯拉丁数字。
 * 但「2000 美元」也该走 number 档,它含汉字——墨迹高度由最高的字形决定,也就是汉字,
 * 用 0.766 会让整行大出 23%。role 说的是"多大一档",字形说的是"这一档怎么换算成 font-size",
 * 两件事不该混在一个表里。
 */
const CJK = /[\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF\u3040-\u30FF]/;
export const inkRatioForText = (text: string) =>
  CJK.test(text) ? INK_RATIO_CJK : INK_RATIO_LATIN;

/**
 * 相对底边的额外下移(占画幅高)。默认 0 = 墨迹底边贴 baseline。
 * 数字档例外:原片的「80%」墨迹是 64–73%,**下探到 baseline 以下 3%**,
 * 也就是它是绕着 68.5% 居中的,不是坐在 70% 上。差 3% 画幅高肉眼看得出来。
 */
export const BASELINE_SHIFT: Partial<Record<Role, number>> = {number: 0.029};

/**
 * 行的水平中心(占画幅宽)。实测原片:标签行 41%,术语行 56%,其余居中。
 *
 * ⚠️ **这是原片的实测值,不是本项目现在的做法。** 2026-08-19 用户在两支片子上都判定
 *    对角错位读起来就是"字幕整体偏右"——即使整块并集数学上正对 0.5 也一样,
 *    因为下面那行更宽更重,它往右挪就带着整体往右倒。**新脚本每一行都写 center: 0.5。**
 *    `tools/lib/caption-spec.mjs` 的 linter 会对不居中的行报警告。
 *
 *    这里的值保持原样是因为 `script-reference.ts`(原片的逐帧副本、整套标定的基准)
 *    有 55/70 行靠这些默认值,改了标定基准就废了。
 *    所以:**默认值属于对标基准,不属于新片子。**
 */
export const CENTER: Record<Role, number> = {
  narration: 0.50,
  label: 0.41,
  term: 0.56,
  emphasis: 0.50,
  node: 0.50,
  number: 0.50,
};

/**
 * 配色 —— 双色制。白讲叙述,琥珀讲结论。
 * 琥珀只发给三种东西:专有名词 / 结论词 / 数字。实测 37% 的秒数出现橙,面积从不超过画面 2%。
 */
export const COLOR = {
  white: '#F9F8F7', // 实测均值
  amber: '#F2A50E', // 实测均值
  /** 缩放弹入时先闪一下的亮黄,再落回 amber。实测 49.6s 那一帧 */
  flash: '#FFD84D',
  /** 逐字写入时跟着笔头走的光点 */
  head: '#FFE47A',
  /** 出场时旧块被压成的灰。实测 61.7–62.9s 的残影 */
  ghost: '#9A948C',
} as const;

/**
 * 硬投影:右下偏移,**不带模糊**。实测偏移约 4px @576 宽 = 0.7% 画幅宽。
 * 这一条和字重一起,让字不需要半透明底板就能压住任何背景——原片全片没有一块底板。
 */
export const SHADOW_OFFSET = 0.007;
/**
 * 硬投影的实际像素:按**画幅短边**算,不是按宽。
 * 竖屏短边就是宽(1080),所以竖屏的数值和标定时一模一样;
 * 横屏如果继续按宽算,0.007 × 1920 = 13.4px 会压在 62px 的字上(21% 字号),
 * 像给每个字加了一条黑杠。按短边算恒为 7.6px,两个比例下都是字号的 11–12%。
 */
export const shadowPx = (width: number, height: number) => SHADOW_OFFSET * Math.min(width, height);

/** 入场动效。时长单位是秒,实测值见 STUDY.md 四、6 */
export const ENTER = {
  /** 横向冲入 + 方向性动态模糊。用于换一整句叙述。实测 27.2→27.5s */
  whip: {duration: 0.30, fromX: 0.42, ghosts: 7},
  /** 缩放弹入 + 黄色辉光闪一下落回琥珀。用于术语落到标签行下方。实测 49.5→49.7s */
  /**
   * `glowRadius` 是辉光半径占**画幅高**的比例,**默认 0 = 不要辉光**。
   *
   * 原来写死 0.03(1920 高上就是 57.6px 的黄色模糊,4K 上翻倍),弹入时整行糊成一团黄。
   * 2026-08-19 用户的原话:「这个第二个词的出现画面太脏」。缩放弹入 + 短暂的亮黄换色
   * 已经足够交代"这是重点",再加一圈大半径辉光只会把字啃掉、把背景弄脏。
   * 真要辉光,给到 0.004(≈8px)封顶,不要再回到 0.03。
   */
  pop: {duration: 0.20, fromScale: 0.62, overshoot: 1.055, glowRadius: 0},
  /** 逐字写入 + 亮黄光点跟着走。用于关键改写句。实测 61.7→62.1s,6 字 0.4 秒 */
  write: {perChar: 0.065},
  /** 硬切。普通叙述行接替时用 */
  cut: {duration: 0},
} as const;

export type EnterKind = keyof typeof ENTER;

/**
 * 出场 —— **默认干净切走,不留残影。**
 *
 * 第一版把 dropTo=0.42 + 1.1 秒慢淡当成了通用规则,结果每一次换块都拖一条影子,
 * 而块间距只有 2 秒多,于是画面上大半时间都有留痕。用户一眼就看出来了。
 *
 * 回去逐帧量原片 15 次换块才发现:**我照抄的是全片唯一的极端个例。**
 * 实测旧字在换块后 +0.3s 的残留:21.7s→1%、82.3s→0%、50.4s→15%、
 * 而 61.7s→49%(那一处是逐字写入的强调句,故意做的重叠)。
 * 多数转场根本没有残影。
 *
 * 所以:默认 ghostOpacity=0(2 帧内切净,只为避免硬跳),
 * 想要重叠的块自己在脚本里写 `"ghost": 0.45`。
 * 而且原片的残影形状是**瞬间掉到某个值 → 平住 → 瞬间归零**,不是缓动淡出。
 */
export const EXIT = {
  /** 默认不留残影。按块覆盖:block.ghost */
  ghostOpacity: 0,
  /** 切净用的帧数。2 帧 ≈ 0.067 秒,在实测噪声以内,只是避免一帧硬跳 */
  cutFrames: 2,
  /** 带残影时:掉到 ghost 值后平住多久,然后瞬间归零 */
  holdSeconds: 1.15,
} as const;

